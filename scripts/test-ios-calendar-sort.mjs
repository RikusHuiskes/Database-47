import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const url=path=>'data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(readFileSync(path,'utf8'))).toString('base64');
const code=stripTypeScriptTypes(readFileSync('app/ios-preview/calendar-reminder.ts','utf8')).replace("'./app-model'",JSON.stringify(url('app/ios-preview/app-model.ts')));
const {canSaveEventDate,createEventDateReminder}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const {filterEvents}=await import(url('app/ios-preview/app-model.ts'));
const {prioritizeHighlighted}=await import(url('lib/event-presentation.ts'));
const now=new Date('2026-11-01T12:00:00Z'),link='https://example.com/ios-preview?event=event-id';
const base={id:'event-id',title:'Kerstdiner Le Nourrissat',start_at:'2026-12-25',address:'Route de Nourissat',city:'Savignac-de-Duras'};
assert.equal(canSaveEventDate(base,now),true);
assert.equal(canSaveEventDate({...base,is_directory_entry:true},now),false);
assert.equal(canSaveEventDate({...base,start_at:'2021-01-01'},now),false);
assert.equal(canSaveEventDate({...base,start_at:'2021-01-01',end_at:'2027-12-31'},now),false);
assert.equal(canSaveEventDate({...base,start_at:'invalid'},now),false);
assert.equal(canSaveEventDate({...base,end_at:'2026-12-24'},now),false);
assert.equal(canSaveEventDate({...base,end_at:'2027-06-01'},now),false);
assert.throws(()=>createEventDateReminder({...base,is_directory_entry:true},link,now),/geen concrete/);
const text=createEventDateReminder(base,link,now),unfold=value=>value.replace(/\r\n /g,'');
assert.ok(text.endsWith('\r\n'));
assert.ok(text.includes('DTSTART;VALUE=DATE:20261225\r\n'));
assert.ok(text.includes('DTEND;VALUE=DATE:20261226\r\n'));
assert.ok(text.includes('DTSTAMP:20261101T120000Z\r\n'));
assert.ok(text.includes('TRANSP:TRANSPARENT\r\n'));
assert.ok(unfold(text).includes('URL:'+link));
assert.ok(unfold(text).includes('Dagnotitie voor de begindatum'));
const midnight=createEventDateReminder({...base,start_at:'2026-12-25T23:30:00Z'},link,now);
assert.ok(midnight.includes('DTSTART;VALUE=DATE:20261226'));
assert.ok(createEventDateReminder({...base,start_at:'2026-12-31'},link,now).includes('DTEND;VALUE=DATE:20270101'));
assert.ok(createEventDateReminder({...base,start_at:'2028-02-29'},link,now).includes('DTEND;VALUE=DATE:20280301'));
const injected=createEventDateReminder({...base,title:'Test\r\nATTENDEE:someone@example.com',short_description:'Example\nBEGIN:VEVENT\nEND:VEVENT'},link,now);
assert.equal(unfold(injected).split('\r\n').filter(line=>line.startsWith('ATTENDEE:')).length,0);
assert.equal(unfold(injected).split('\r\n').filter(line=>line==='BEGIN:VEVENT').length,1);
const unicode=createEventDateReminder({...base,title:'Été 🏰 dégustation '.repeat(30)},link,now);
assert.ok(unicode.split('\r\n').every(line=>Buffer.byteLength(line,'utf8')<=75));
assert.ok(unfold(unicode).includes('SUMMARY:'+'Été 🏰 dégustation '.repeat(30)));
assert.equal(unfold(createEventDateReminder(base,'javascript:alert(1)',now)).split('\r\n').some(line=>line.startsWith('URL:')),false);
assert.equal(text.replace(/\r\n/g,'').includes('\n'),false);
const options={query:'',when:'all',kind:'all',city:'',radius:50,freeOnly:false,sort:'distance'};
const events=[{...base,id:'far',title:'Zulu',distance_km:20},{...base,id:'unknown',title:'Unknown'},{...base,id:'near',title:'Alpha',distance_km:0}];
assert.deepEqual(filterEvents(events,options,now).map(item=>item.id),['near','far','unknown']);
assert.deepEqual(events.map(item=>item.id),['far','unknown','near']);
assert.deepEqual(filterEvents(events,{...options,sort:'name'},now).map(item=>item.title),['Alpha','Unknown','Zulu']);
const promoted={...events[0],advertising_placements:[{placement:'highlight',starts_at:'2026-01-01',ends_at:'2027-01-01'}]};
assert.equal(prioritizeHighlighted(filterEvents([events[2],promoted],options,now),now)[0].id,'far');
console.log('28 checks passed: date reminders, France timezone, leap/year boundaries, RFC folding, injection protection and promotion-aware sorting.');
