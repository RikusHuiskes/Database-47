import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const code=stripTypeScriptTypes(readFileSync('app/ios-preview/app-model.ts','utf8'));
const {calendarDay,eventDate,matchesDate,filterEvents}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const sunday=new Date('2026-11-01T10:00:00Z');
const base={id:'a',title:'Dégustation à Duras',start_at:'2026-11-02',city:'Duras',address:'Place du Château',distance_km:0,is_free:true};
const options={query:'',when:'all',kind:'all',city:'',radius:50,freeOnly:false};
assert.equal(calendarDay('2026-10-31T23:30:00Z'),'2026-11-01');
assert.equal(calendarDay('2026-03-29T22:30:00Z'),'2026-03-30');
assert.equal(calendarDay('2026-12-25'),'2026-12-25');
assert.equal(matchesDate(base,'tomorrow',sunday),true);
assert.equal(matchesDate(base,'weekend',sunday),false);
assert.equal(matchesDate({...base,start_at:'2026-10-31',end_at:'2026-11-01'},'weekend',sunday),true);
assert.equal(matchesDate({...base,is_directory_entry:true},'today',sunday),false);
assert.equal(matchesDate({...base,start_at:'2026-11-07'},'week',sunday),true);
assert.equal(matchesDate({...base,start_at:'2026-11-08'},'week',sunday),false);
assert.equal(matchesDate({...base,start_at:'2026-10-01',end_at:'2026-11-03'},'today',sunday),true);
assert.equal(eventDate({...base,start_at:'2022-01-01',end_at:'2026-12-31'},sunday),'Loopt t/m 31 december 2026');
assert.equal(eventDate({...base,is_directory_entry:true},sunday),'Het hele jaar ontdekken');
assert.equal(filterEvents([base],{...options,query:'degustation'},sunday).length,1);
assert.equal(filterEvents([base],{...options,query:'chateau'},sunday).length,1);
assert.equal(filterEvents([base],{...options,radius:10},sunday).length,1);
assert.equal(filterEvents([{...base,distance_km:undefined}],{...options,radius:10},sunday).length,0);
assert.equal(filterEvents([{...base,is_free:null}],{...options,freeOnly:true},sunday).length,0);
assert.equal(filterEvents([base],{...options,city:'Bergerac'},sunday).length,0);
assert.equal(filterEvents([base,{...base,id:'b',is_directory_entry:true}],{...options,kind:'events'},sunday).length,1);
console.log('18 checks passed: France dates, DST, weekend boundaries, date ranges, accents, addresses, price and distance filters.');
