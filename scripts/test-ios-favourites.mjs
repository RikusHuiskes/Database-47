import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const code=stripTypeScriptTypes(readFileSync('app/ios-preview/saved-entries.ts','utf8'));
const {decodeSavedEntries,savedEventNotice}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const event={kind:'event',item:{id:'a',title:'Kerstdiner',start_at:'2026-12-25'},savedAt:1793550000000};
const service={kind:'service',item:{id:'a',name:'Bakkerij',type:'bakery'}};
assert.deepEqual(decodeSavedEntries('broken'),[]);
assert.deepEqual(decodeSavedEntries('{}'),[]);
assert.equal(decodeSavedEntries(JSON.stringify([event,service])).length,2);
assert.equal(decodeSavedEntries(JSON.stringify([event,event])).length,1);
assert.equal(decodeSavedEntries(JSON.stringify([{...event,item:{id:'a'}}])).length,0);
assert.equal(decodeSavedEntries(JSON.stringify([{...service,item:{...service.item,name:{bad:true}}}])).length,0);
assert.equal(decodeSavedEntries(JSON.stringify([{...event,item:{...event.item,category_ids:[{}]}}])).length,0);
assert.equal(decodeSavedEntries(JSON.stringify([{...event,item:{...event.item,advertising_placements:[null]}}])).length,0);
assert.equal(decodeSavedEntries(JSON.stringify([{...event,item:{...event.item,distance_km:'far'}}])).length,0);
assert.equal(decodeSavedEntries(JSON.stringify([{...event,savedAt:'bad'}]))[0].savedAt,undefined);
assert.equal(decodeSavedEntries(JSON.stringify(Array.from({length:210},(_,i)=>({...event,item:{...event.item,id:String(i)}})))).length,200);
const live=new Map([['a',{...event.item,title:'Nieuwe titel'}]]);
assert.equal(savedEventNotice(event.item,live,true,false),'Actuele agendagegevens');
assert.match(savedEventNotice(event.item,live,false,false),/wordt gecontroleerd/);
assert.match(savedEventNotice(event.item,live,true,true),/niet bereikbaar/);
assert.match(savedEventNotice(event.item,new Map(),true,false),/Niet meer gevonden/);
console.log('15 checks passed: existing favourites retained, invalid storage rejected, duplicates and cap, live/loading/error/missing statuses.');
