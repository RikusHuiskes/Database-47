import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const moduleUrl=path=>'data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(readFileSync(path,'utf8'))).toString('base64');
const savedUrl=moduleUrl('app/ios-preview/saved-entries.ts');
const backupCode=stripTypeScriptTypes(readFileSync('app/ios-preview/favourites-backup.ts','utf8')).replace("'./saved-entries'",JSON.stringify(savedUrl));
const {createFavouritesBackup,readFavouritesBackup,mergeFavourites}=await import('data:text/javascript;base64,'+Buffer.from(backupCode).toString('base64'));
const {parseSharedRequest,sharedEntryUrl}=await import(moduleUrl('app/ios-preview/shared-links.ts'));
const origin='https://example.com';
const event={kind:'event',item:{id:'4ae2d2b9-623d-4c90-9517-9d4da5d9fcc6',title:'Kerstdiner',start_at:'2026-12-25'},savedAt:123456};
const address={kind:'service',item:{id:'osm:way/123?x=1&y=2',name:'Pharmacie du Château',type:'pharmacy',website:'https://example.com/apotheek'},context:{townId:'duras',serviceType:'pharmacy'}};
assert.equal(parseSharedRequest('', ['duras'],['pharmacy']),null);
assert.equal(parseSharedRequest('?event=bad',['duras'],['pharmacy']).kind,'invalid');
assert.equal(parseSharedRequest('?event=',['duras'],['pharmacy']).kind,'invalid');
assert.equal(parseSharedRequest('?service=x&town=sarlat&type=pharmacy',['duras'],['pharmacy']).kind,'invalid');
assert.equal(parseSharedRequest('?service=x&town=duras&type=unknown',['duras'],['pharmacy']).kind,'invalid');
assert.equal(parseSharedRequest('?service=x&event=bad&town=duras&type=pharmacy',['duras'],['pharmacy']).kind,'invalid');
assert.equal(parseSharedRequest('?service=&town=duras&type=pharmacy',['duras'],['pharmacy']).kind,'invalid');
const serviceUrl=sharedEntryUrl(address,origin);
assert.equal(new URL(serviceUrl).origin,origin);
assert.deepEqual(parseSharedRequest(new URL(serviceUrl).search,['duras'],['pharmacy']),{kind:'service',id:address.item.id,townId:'duras',serviceType:'pharmacy'});
assert.deepEqual(parseSharedRequest(new URL(sharedEntryUrl(event,origin)).search,['duras'],['pharmacy']),{kind:'event',id:event.item.id});
assert.equal(sharedEntryUrl({...address,context:undefined},origin),address.item.website);
assert.equal(sharedEntryUrl({...address,context:undefined,item:{...address.item,website:'javascript:bad'}},origin),origin+'/ios-preview');
const backup=createFavouritesBackup([event,address],new Date('2026-11-01T12:00:00Z'));
assert.equal(JSON.parse(backup).format,'cote-de-duras-favourites');
assert.deepEqual(readFavouritesBackup(backup),[event,address]);
assert.throws(()=>readFavouritesBackup('{}'),/Cote de Duras/);
assert.throws(()=>readFavouritesBackup('bad'),/leesbare reservekopie/);
assert.throws(()=>readFavouritesBackup(JSON.stringify({...JSON.parse(backup),format:'cote-de-sarlat-favourites'})),/Cote de Duras/);
assert.throws(()=>readFavouritesBackup(JSON.stringify({...JSON.parse(backup),version:2})),/Cote de Duras/);
assert.throws(()=>readFavouritesBackup(JSON.stringify({...JSON.parse(backup),entries:[event,event]})),/dubbele/);
assert.throws(()=>readFavouritesBackup(JSON.stringify({...JSON.parse(backup),entries:[{kind:'service',item:{id:'a',name:{bad:true},type:'pharmacy'}}]})),/ongeldige/);
const merged=mergeFavourites([event],[event,address]);
assert.equal(merged.added,1);assert.equal(merged.entries.length,2);assert.equal(merged.entries[0].item.title,'Kerstdiner');
const full=Array.from({length:200},(_,i)=>({...event,item:{...event.item,id:String(i)}}));
assert.equal(mergeFavourites(full,[address]).entries.length,200);
assert.equal(mergeFavourites(full,[address]).added,0);
assert.equal(mergeFavourites(full,[address]).atCapacity,true);
const publicOnly=createFavouritesBackup([{...event,manageKey:'private-test',item:{...event.item,privateToken:'private-test'}}]);
assert.equal(publicOnly.includes('private-test'),false);
assert.equal(publicOnly.includes('manageKey'),false);
console.log('28 checks passed: service/event links, context validation, backup round trips, wrong site/version, invalid content, merge and privacy.');
